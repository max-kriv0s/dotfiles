-- Сессия — это снимок рабочего места: какие файлы открыты, как разбит экран,
-- какие вкладки. Привязывается к каталогу, поэтому вернувшись в проект,
-- можно восстановить всё, как было при выходе.
return {
  "rmagatti/auto-session",
  -- Восстановление происходит на старте, отложенная загрузка его сломает
  lazy = false,
  opts = {
    -- Сохранение автоматическое, восстановление — по клавише.
    -- Иначе `nvim файл.ts` в каталоге с сессией открыл бы не файл,
    -- а всё прошлое рабочее место поверх него.
    auto_restore = false,

    -- В этих каталогах сессии не имеют смысла: там не работают,
    -- туда заходят посмотреть файл
    suppressed_dirs = { "~/", "~/Downloads", "~/Documents", "~/Desktop" },
  },
  keys = {
    -- В сборке B были SessionRestore и SessionSave — они объявлены устаревшими
    { "<leader>wr", "<cmd>AutoSession restore<CR>", desc = "Восстановить сессию каталога" },
    { "<leader>цк", "<cmd>AutoSession restore<CR>", desc = "Восстановить сессию каталога (рус)" },
    { "<leader>ws", "<cmd>AutoSession save<CR>", desc = "Сохранить сессию каталога" },
    { "<leader>цы", "<cmd>AutoSession save<CR>", desc = "Сохранить сессию каталога (рус)" },
  },
}
